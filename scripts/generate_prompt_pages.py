#!/usr/bin/env python3
"""Render authored prompt cards into site pages. Called by generate_prompt_catalogue.py."""

from __future__ import annotations

import argparse
import html
import json
import posixpath
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

from prompt_metadata import (
    ROOT, PROMPTS_DIR, PAGES_DIR, METADATA, PAGES, MAPPING,
    KNOWN_SITE_LESS_CARDS, fenced_parts, full_prompt_blocks,
)


def page_url(page: dict) -> str:
    return f'/frontier-analytics-prompt-{page["slug"]}/'


def rewrite_links(text: str, source: str) -> str:
    targets = dict(METADATA["links"])
    targets.update({
        "frontier-analytics/prompts/" + page["source"]: page_url(page)
        for page in PAGES
    })
    targets.update({
        "frontier-analytics/prompts/" + card:
            "https://github.com/microsoft/viva-insights-sample-code/blob/main/frontier-analytics/prompts/" + card
        for card in KNOWN_SITE_LESS_CARDS
    })

    def replace(match):
        label, target = match.groups()
        url = urlsplit(target)
        if url.scheme or url.netloc or target.startswith(("#", "/")):
            return match.group(0)
        resolved = posixpath.normpath(posixpath.join("frontier-analytics/prompts", posixpath.dirname(source), url.path))
        if resolved not in targets:
            raise ValueError(f"{source}: unmapped relative link {target!r}")
        mapped = targets[resolved]
        if mapped.startswith("/"):
            mapped = "{{ site.baseurl }}" + mapped
        suffix = ("?" + url.query if url.query else "") + ("#" + url.fragment if url.fragment else "")
        return f"[{label}]({mapped}{suffix})"

    return re.sub(r"\[([^\]\n]+)\]\(([^)\n]+)\)", replace, text)


def render_page(page: dict, source_text: str) -> str:
    full_prompt_blocks(source_text)
    badges = page.get("badges", {})
    fields = {
        "layout": "page",
        "title": page["title"],
        "eyebrow": "Frontier · Prompt library" if badges else "Frontier",
        "permalink": page_url(page),
    }
    if "description" in page:
        fields["description"] = page["description"]
    front = "---\n" + "".join(f"{key}: {json.dumps(value, ensure_ascii=False)}\n" for key, value in fields.items())
    if badges:
        # Retain historical evidence metadata, not a claim of revalidation.
        validated = page.get("last_validated", METADATA["last_validated"])
        if validated:
            front += f"last_validated: {validated}\n"
        front += "badges:\n"
        front += "".join(f"  {key}: {json.dumps(value, ensure_ascii=False)}\n" for key, value in badges.items())
    front += "---\n<!-- Generated by scripts/generate_prompt_catalogue.py. Edit the source card and scripts/prompt_pages.json. -->\n"
    front += "{% include prompt-styles.html %}\n\n"
    back = "[← Back to Prompt Library]({{ site.baseurl }}/frontier-analytics-prompts/)"
    if not badges:
        back += " · [View dashboard examples]({{ site.baseurl }}/copilot-dashboards/)"
    intro = back + "\n\n"
    if badges:
        intro += '> **📋 Review the schema first.** Before running this prompt, confirm your column names and the Copilot/agent action taxonomy against the **[Schema Documentation]({{ site.baseurl }}/frontier-analytics-schemas/)**.\n\n'
        intro += "{% include prompt-badges.html %}\n\n{% include last-validated.html %}\n\n"

    parts = []
    inserted = False
    for fenced, part in fenced_parts(source_text):
        if fenced:
            # Liquid must not evaluate user-facing prompt syntax or code samples.
            parts.append("{% raw %}\n" + part + "{% endraw %}\n")
            continue
        for heading, alias in page.get("heading_aliases", {}).items():
            part = re.sub(rf"^{re.escape(heading)}$", f'<span id="{alias}"></span>\n\n{heading}', part, flags=re.M)
        part = rewrite_links(part, page["source"])
        if not inserted:
            title = re.search(r"^# .+\n", part, re.M)
            if title:
                part = part[:title.end()] + "\n" + intro + part[title.end():].lstrip("\n")
                if "title_anchor" in page:
                    part = f'<span id="{page["title_anchor"]}"></span>\n\n' + part
            else:
                part = intro + part
            inserted = True
        parts.append(part)

    result = front + "".join(parts).rstrip() + "\n\n{% include responsible-use.html %}\n"
    navigation = METADATA["navigation"]
    if page["slug"] in navigation:
        position = navigation.index(page["slug"])
        by_slug = {item["slug"]: item for item in PAGES}
        nav = []
        for offset, label in [(-1, "Previous"), (1, "Next")]:
            index = position + offset
            if 0 <= index < len(navigation):
                neighbour = by_slug[navigation[index]]
                caption = html.escape(neighbour["nav_label"])
                caption = f"← Previous: {caption}" if offset == -1 else f"Next: {caption} →"
                nav.append(f'  <a href="{{{{ site.baseurl }}}}{page_url(neighbour)}">{caption}</a>')
            else:
                caption = "← Previous" if offset == -1 else "Next →"
                nav.append(f'  <span class="nav-disabled">{caption}</span>')
        result += '\n<div class="prompt-nav">\n' + "\n".join(nav) + "\n</div>\n"
    return result


def generated_pages() -> dict[Path, str]:
    cards = {
        path.relative_to(PROMPTS_DIR).as_posix()
        for path in PROMPTS_DIR.rglob("*.md") if path.name != "README.md"
    }
    expected = set(MAPPING) | KNOWN_SITE_LESS_CARDS
    if cards != expected or set(MAPPING) & KNOWN_SITE_LESS_CARDS:
        raise ValueError(f"Unmapped/missing prompt cards: {sorted(cards ^ expected)}")
    names = list(MAPPING.values())
    if len(names) != len(set(names)):
        raise ValueError("Duplicate prompt page route")
    orphans = {p.name for p in PAGES_DIR.glob("frontier-analytics-prompt-*.md")} - set(names)
    if orphans:
        raise ValueError(f"Orphan site prompt pages: {sorted(orphans)}")
    return {
        PAGES_DIR / MAPPING[page["source"]]:
            render_page(page, (PROMPTS_DIR / page["source"]).read_text(encoding="utf-8"))
        for page in PAGES
    }


def sync_pages(check: bool) -> bool:
    stale = False
    for path, expected in generated_pages().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                print(f"Stale generated page: {path.name}", file=sys.stderr)
                stale = True
        else:
            path.write_text(expected, encoding="utf-8")
    return not stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    return 0 if sync_pages(parser.parse_args().check) else 1


if __name__ == "__main__":
    sys.exit(main())
